interface PresidentSeed {
  id: string;
  region: PresidentRegion;
  name: string;
  title: string;
  era: string;
  role: string;
  taunt: string;
  stats: PresidentData['stats'];
  skin: string;
  suit: string;
  accent: string;
  hair: string;
  boots?: string;
  build: BodyBuild;
  outfit: AnatomicalProfile['outfitStyle'];
  cape?: string;
  weapon: AnatomicalProfile['weaponType'];
  hatOrHair: AnatomicalProfile['hatOrHair'];
  tieOrSash: AnatomicalProfile['tieOrSash'];
  glasses?: boolean;
  holster?: boolean;
  kneepads?: boolean;
  face: AnatomicalProfile['face'];
  sigType: keyof typeof SIGNATURE_TEMPLATES;
  sigName: string;
  powerSourceId: keyof typeof ULT_LIBRARY;
  ultName: string;
  ultCry: string;
}

function buildPresident(s: PresidentSeed): PresidentData {
  const bp = BODY_BUILD_PRESETS[s.build];
  const ultInfo = ULT_LIBRARY[s.powerSourceId];
  return {
    id: s.id,
    powerSourceId: s.powerSourceId,
    region: s.region,
    name: s.name,
    title: s.title,
    era: s.era,
    role: s.role,
    taunt: s.taunt,
    stats: s.stats,
    palette: {
      skin: makeColorRamp(s.skin),
      suit: makeColorRamp(s.suit),
      accent: makeColorRamp(s.accent),
      hair: s.hair,
      hairShadow: shiftHex(s.hair, -45),
      boots: s.boots || '#13161f',
    },
    anatomy: {
      bodyBuild: s.build,
      heightScale: bp.heightScale,
      shoulderWidth: bp.shoulderWidth,
      chestWidth: bp.chestWidth,
      waistWidth: bp.waistWidth,
      armThickness: bp.armThickness,
      legThickness: bp.legThickness,
      headRadius: bp.headRadius,
      outfitStyle: s.outfit,
      hasCapeOrCoat: Boolean(s.cape),
      capeColor: s.cape,
      capeShadow: s.cape ? shiftHex(s.cape, -34) : undefined,
      weaponType: s.weapon,
      hatOrHair: s.hatOrHair,
      tieOrSash: s.tieOrSash,
      glasses: Boolean(s.glasses),
      holster: Boolean(s.holster),
      kneepads: Boolean(s.kneepads),
      face: s.face,
    },
    signatureType: s.sigType,
    sigName: s.sigName,
    sig: structuredClone(SIGNATURE_TEMPLATES[s.sigType]),
    ult: {
      name: s.ultName,
      cry: s.ultCry,
      sigDesc: ultInfo.sigDescPrefix,
      ultDesc: ultInfo.ultDesc,
      dodgeTip: ultInfo.dodgeTip,
    },
  };
}

