function shiftHex(hex: string, amt: number): string {
  const clean = hex.replace('#', '');
  const num = parseInt(clean.length === 3 ? clean.split('').map((c) => c + c).join('') : clean, 16);
  const r = Math.max(0, Math.min(255, ((num >> 16) & 255) + amt));
  const g = Math.max(0, Math.min(255, ((num >> 8) & 255) + amt));
  const b = Math.max(0, Math.min(255, (num & 255) + amt));
  return '#' + ((1 << 24) + (r << 16) + (g << 8) + b).toString(16).slice(1);
}

export function makeColorRamp(base: string): ColorRamp {
  return {
    base,
    shadow: shiftHex(base, -42),
    highlight: shiftHex(base, 36),
    outline: shiftHex(base, -110),
  };
}

